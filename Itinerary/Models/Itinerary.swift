import Foundation

/// Category of an itinerary item. It drives the color and icon of the event.
enum ItineraryItemKind: String, Codable, CaseIterable {
    case activity
    case travel
    case routine
    case fixed
    case meal
    case rest

    /// Maps the free-form `kind` returned by the LLM to a known category.
    init(llmValue: String?) {
        let value = (llmValue ?? "").lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
        switch value {
        case "travel", "commute", "transport", "transit", "trip": self = .travel
        case "routine", "habit", "daily": self = .routine
        case "fixed", "event", "appointment", "meeting", "calendar": self = .fixed
        case "meal", "food", "breakfast", "lunch", "dinner": self = .meal
        case "break", "rest", "free", "free time", "buffer": self = .rest
        default: self = .activity
        }
    }

    var title: String {
        switch self {
        case .activity: return String(localized: "Activity")
        case .travel: return String(localized: "Travel")
        case .routine: return String(localized: "Routine")
        case .fixed: return String(localized: "Fixed event")
        case .meal: return String(localized: "Meal")
        case .rest: return String(localized: "Break")
        }
    }

    var symbol: String {
        switch self {
        case .activity: return "checklist"
        case .travel: return "car.fill"
        case .routine: return "repeat"
        case .fixed: return "calendar"
        case .meal: return "fork.knife"
        case .rest: return "cup.and.saucer.fill"
        }
    }
}

/// A single scheduled block of the day.
struct ItineraryItem: Codable, Identifiable, Hashable {
    var id = UUID()
    var title: String
    var start: Date
    var end: Date
    var kind: ItineraryItemKind
    var location: String?
    var notes: String?

    var durationMinutes: Int {
        max(0, Int((end.timeIntervalSince(start) / 60).rounded()))
    }
}

/// A one-day plan generated by the LLM.
struct Itinerary: Codable, Identifiable {
    var id = UUID()
    /// Start of the planned day.
    var day: Date
    var items: [ItineraryItem]
    var summary: String
    var unscheduled: [String]
    var transcript: String
    var createdAt: Date
    var providerName: String
    var model: String

    var dayKey: String { DayKey.make(for: day) }
}

/// Stable string identifier for a calendar day, e.g. `2026-10-24`.
enum DayKey {
    static func make(for date: Date, calendar: Calendar = .current) -> String {
        let components = calendar.dateComponents([.year, .month, .day], from: date)
        return String(format: "%04d-%02d-%02d", components.year ?? 0, components.month ?? 0, components.day ?? 0)
    }
}
